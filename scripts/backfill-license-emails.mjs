#!/usr/bin/env node
/**
 * Backfill licenses.email_hash from Stripe — one-shot, run once after the v5
 * migration + Worker deploy. This is what recovers customers who bought
 * BEFORE recover-by-email existed: their licence rows have email_hash = NULL,
 * so /recover can't find them until this fills the column.
 *
 * It is reliable because `customer_details.email` is present on every paid
 * Stripe Checkout Session (Stripe collects the email at payment), independent
 * of whether a Customer object was created.
 *
 * We only ever store HMAC(SALT, email) — never the raw address. The generated
 * SQL contains hex hashes only (no PII), and UPDATEs no-op when no licence row
 * matches a session, so it is safe to over-generate.
 *
 * Usage (PowerShell):
 *   $env:STRIPE_SECRET_KEY = "sk_live_..."   # same key as the Worker secret
 *   $env:HMAC_SALT         = "..."           # MUST equal the Worker HMAC_SALT
 *   node scripts/backfill-license-emails.mjs           # generate SQL only
 *   node scripts/backfill-license-emails.mjs --apply   # generate AND run wrangler
 *
 * A wrong HMAC_SALT silently produces hashes that match nothing — double-check
 * it equals the value set via `wrangler secret put HMAC_SALT`.
 */

import { createHmac } from "node:crypto";
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const STRIPE_SECRET_KEY = process.env.STRIPE_SECRET_KEY;
const HMAC_SALT = process.env.HMAC_SALT;
const APPLY = process.argv.includes("--apply");
const DB_NAME = "wfc-community";

if (!STRIPE_SECRET_KEY || !HMAC_SALT) {
  console.error("ERROR: set STRIPE_SECRET_KEY and HMAC_SALT env vars (the same values as the Worker secrets).");
  process.exit(1);
}

// Byte-identical to the Worker's hmacHex(salt, data): HMAC-SHA256, key = UTF-8
// bytes of salt, lowercase hex output.
function hmacHex(salt, data) {
  return createHmac("sha256", Buffer.from(salt, "utf8")).update(Buffer.from(data, "utf8")).digest("hex");
}

// Identical to the Worker's normalizeEmail — keep the two in lockstep.
function normalizeEmail(email) {
  if (typeof email !== "string") return "";
  const e = email.trim().toLowerCase();
  if (e.length > 254 || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(e)) return "";
  return e;
}

async function* iterCheckoutSessions() {
  let startingAfter = null;
  while (true) {
    const params = new URLSearchParams({ limit: "100" });
    if (startingAfter) params.set("starting_after", startingAfter);
    const res = await fetch(`https://api.stripe.com/v1/checkout/sessions?${params}`, {
      headers: { Authorization: `Bearer ${STRIPE_SECRET_KEY}` },
    });
    if (!res.ok) {
      throw new Error(`Stripe ${res.status}: ${await res.text()}`);
    }
    const page = await res.json();
    for (const s of page.data) yield s;
    if (!page.has_more || page.data.length === 0) break;
    startingAfter = page.data[page.data.length - 1].id;
  }
}

async function main() {
  let scanned = 0;
  let paid = 0;
  let withEmail = 0;
  const statements = [];

  for await (const s of iterCheckoutSessions()) {
    scanned++;
    if (scanned % 200 === 0) console.error(`  …scanned ${scanned} sessions`);
    if (s.payment_status !== "paid") continue;
    paid++;
    const email = normalizeEmail(s.customer_details?.email);
    if (!email) continue;
    withEmail++;
    const sessionIdHash = hmacHex(HMAC_SALT, s.id);
    const emailHash = hmacHex(HMAC_SALT, email);
    // Values are HMAC hex → no quoting/injection concerns. The guard never
    // overwrites a hash already set (e.g. by a re-verify after deploy).
    statements.push(
      `UPDATE licenses SET email_hash = '${emailHash}' WHERE session_id_hash = '${sessionIdHash}' AND email_hash IS NULL;`,
    );
  }

  console.error(`\nScanned ${scanned} session(s) — ${paid} paid, ${withEmail} with a usable email.`);
  if (statements.length === 0) {
    console.error("Nothing to backfill.");
    return;
  }

  const here = dirname(fileURLToPath(import.meta.url));
  const outFile = join(here, "backfill-emails.generated.sql");
  const header =
    `-- Generated by backfill-license-emails.mjs — ${statements.length} UPDATE(s).\n` +
    `-- Values are HMAC hex (no PII). UPDATEs no-op when no licence row matches.\n`;
  writeFileSync(outFile, header + statements.join("\n") + "\n", "utf8");
  console.error(`Wrote ${statements.length} UPDATE statement(s) to ${outFile}`);

  if (!APPLY) {
    console.error("\nReview it, then apply with:");
    console.error(`  npx wrangler d1 execute ${DB_NAME} --remote --file scripts/backfill-emails.generated.sql`);
    console.error("\n(or re-run with --apply to run wrangler for you.)");
    return;
  }

  console.error("\nApplying via wrangler…");
  const isWin = process.platform === "win32";
  const npx = isWin ? "npx.cmd" : "npx";
  // Node's CVE-2024-27980 mitigation refuses to launch .cmd/.bat shims via
  // execFileSync unless shell:true is set (it throws EINVAL otherwise). All
  // args here are script-controlled constants (no user input, no spaces), so
  // enabling the shell on Windows is safe.
  execFileSync(npx, ["wrangler", "d1", "execute", DB_NAME, "--remote", "--file", outFile], {
    stdio: "inherit",
    shell: isWin,
  });
  console.error("Backfill applied.");
}

main().catch((e) => {
  console.error("Backfill failed:", e?.message || e);
  process.exit(1);
});
