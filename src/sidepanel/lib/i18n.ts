export function getStoredLang(): string {
  try {
    const stored = localStorage.getItem("wav_lang");
    if (stored) return stored;
    // U-L1 : à défaut de choix enregistré, initialise sur la langue du navigateur
    // (mappée fr/en/es) au lieu de forcer le français.
    const nav = (navigator.language || "").slice(0, 2).toLowerCase();
    return ["fr", "en", "es"].includes(nav) ? nav : "fr";
  } catch {
    return "fr";
  }
}

export function setStoredLang(lang: string): void {
  try {
    localStorage.setItem("wav_lang", lang);
  } catch {
    // ignore
  }
  // Sync vers chrome.storage.local pour que le service worker puisse lire la langue
  chrome.storage.local.set({ wav_lang: lang }).catch(() => {});
}

export function t(key: string, lang: string): string {
  return translations[lang]?.[key] || translations.fr[key] || key;
}
